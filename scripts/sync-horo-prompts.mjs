#!/usr/bin/env node
// Regenerate cloudflare-worker/src/horo-prompts.js from prompts/0*.md.
//
// prompts/*.md is the single source of truth for the horo_consult stage
// prompts (KAN-204). The worker is a Cloudflare Worker, so it cannot read
// files at runtime — this script extracts the fenced prompt block from each
// stage file and embeds it verbatim into the generated module. Edit the .md
// file, re-run this script, commit both.
//
// Usage: node scripts/sync-horo-prompts.mjs   (from repo root or worker dir)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..");
const promptsDir = join(repoRoot, "prompts");
const outPath = join(repoRoot, "cloudflare-worker", "src", "horo-prompts.js");

const STAGES = [
  { id: "birth-chart", file: "01-birth-chart.md", heading: "แผนภูมิกำเนิด (Birth Chart)" },
  { id: "base-fortune", file: "02-base-fortune.md", heading: "ดวงพื้นฐาน (Base Fortune)" },
  { id: "turning-points", file: "03-turning-points.md", heading: "จุดเปลี่ยน (Turning Points)" },
  { id: "forecast", file: "04-forecast.md", heading: "พยากรณ์อนาคต (Future Forecast)" },
  { id: "additional-insights", file: "05-additional-insights.md", heading: "ข้อควรระวัง (Additional Insights)" }
];

// The first fenced block in each stage file is the prompt body. The yearly
// variant in 04-forecast.md is the runtime default; the finer-granularity
// variants stay documentation-only (the ladder is measured to refuse beyond
// yearly without splitting per conversation).
function extractPromptBlock(md) {
  const match = md.match(/```([a-z]*)\n([\s\S]*?)\n```/);
  if (!match) throw new Error(`No fenced prompt block found`);
  return match[2];
}

const entries = STAGES.map(({ id, file, heading }) => {
  const md = readFileSync(join(promptsDir, file), "utf8");
  const body = extractPromptBlock(md);
  return `  "${id}": {\n    heading: ${JSON.stringify(heading)},\n    template: ${JSON.stringify(body)}\n  }`;
});

const generated = `// GENERATED by scripts/sync-horo-prompts.mjs from prompts/0*.md — do not edit
// by hand. Edit the .md stage file and re-run the script; commit both together.
//
// One atomic request per stage (KAN-204): the notebook is consumed per message,
// so every stage is its own attach + typed-path round trip, and each section
// grounds or fails on its own. The prompts/*.md commentary carries the measured
// evidence for the split; the guardrail contract asserted below is documented
// in prompts/README.md ("The shared guardrail block").

export const HORO_STAGE_IDS = [
${STAGES.map((s) => `  "${s.id}"`).join(",\n")}
];

export const HORO_STAGE_HEADINGS = {
${STAGES.map((s) => `  "${s.id}": ${JSON.stringify(s.heading)}`).join(",\n")}
};

// Verbatim prompt bodies from prompts/0*.md. {{PLACEHOLDER}} tokens are
// interpolated by buildHoroStagePrompt().
export const HORO_STAGE_TEMPLATES = {
${entries.join(",\n")}
};

// Guardrail markers every stage template must carry. Documented in
// prompts/README.md; asserted at build time so a prompt edit that silently
// drops a clause fails loudly here instead of degrading grounding in
// production.
const GUARDRAIL_MARKERS = [
  "ตรวจสอบด้วยวิธีการของคุณเท่านั้น ไม่ใช้ความรู้ทั่วไป", // method-only opener
  "บอกตรงๆ ว่าไม่มี", // honesty clause
  "อ้างอิงแหล่งที่มาใน Notebook ทุกประเด็น", // citation clause
  "ตอบเป็นภาษาไทย" // language clause
];

function assertGuardrails(stageId, template) {
  for (const marker of GUARDRAIL_MARKERS) {
    if (!template.includes(marker)) {
      throw new Error(\`Stage '\${stageId}' prompt lost the guardrail clause: \${marker}\`);
    }
  }
}

for (const stageId of HORO_STAGE_IDS) {
  assertGuardrails(stageId, HORO_STAGE_TEMPLATES[stageId].template);
}

/**
 * Interpolate {{PLACEHOLDER}} tokens for one stage.
 *
 * Missing optional placeholders stay visible as the raw token rather than
 * "undefined": a prompt that silently reads "{{FROM_YEAR}}" pasted into Gemini
 * is recoverable at a glance, an "undefined" year is not.
 *
 * @param {string} stageId one of HORO_STAGE_IDS
 * @param {Record<string, string|number>} params placeholder values
 * @returns {string} the prompt to type into the Gemini tab
 */
export function buildHoroStagePrompt(stageId, params = {}) {
  const stage = HORO_STAGE_TEMPLATES[stageId];
  if (!stage) throw new Error(\`Unknown horo stage '\${stageId}'\`);
  return stage.template.replace(/\\{\\{([A-Z_]+)\\}\\}/g, (token, key) => {
    const value = params[key];
    if (value === undefined || value === null || String(value).trim() === "") return token;
    return String(value);
  });
}

/**
 * Assemble the five grounded stage answers into the TEMPLATE.md document.
 * Concatenation is literal: title, then the five answers in stage order —
 * each already opens with its own fixed ## heading.
 */
export function assembleHoroReading(title, stageOutputs) {
  const parts = ["# " + title, ""];
  for (const stageId of HORO_STAGE_IDS) {
    const output = stageOutputs[stageId];
    if (!output || !output.text) continue;
    parts.push(output.text.trim(), "");
  }
  return parts.join("\\n").trim();
}
`;

writeFileSync(outPath, generated);
console.log(`Wrote ${outPath} (${generated.length} bytes) from prompts/0*.md`);
